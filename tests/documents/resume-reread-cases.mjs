export async function resumeRereadCases({db,as,denied,check,uid}) {
 const spaces=async(n=1)=>(await as(n,'select * from public.passo_workspaces()')).map(w=>w.id);
 await as(1,'select public.passo_open_workspace(3)');
 check('org owner visit without explicit membership is restored',(await spaces()).join()==='3,1');
 check('last workspace is scoped to account',(await spaces(3)).join()==='1');
 await denied('cannot save foreign workspace visit',()=>as(1,'select public.passo_open_workspace(2)'));
 await denied('anonymous cannot save workspace visit',()=>as(1,'select public.passo_open_workspace(1)',[],'anon'));
 await denied('cannot read other account visit history',()=>as(1,'select * from passo_private.workspace_visits'));
 check('expired session cannot restore workspace',(await as(1,'select * from public.passo_workspaces()',[],'authenticated',{exp:1})).length===0);
 await db.exec('delete from org_members where user_id=1');
 check('revoked recent workspace falls back to accessible one',(await spaces()).join()==='1');
 await db.exec("insert into org_members(org_id,user_id,role) values(1,1,'주인')");
 await as(1,'select public.passo_open_workspace(1)');
 check('explicit later visit replaces restored default',(await spaces()).join()==='1,3');
 const j=(await as(1,'select (public.passo_reserve_document(1,$1,$2,$3,$4,$5)).*',[uid(1800),'a'.repeat(64),'image/png',120,'reread.png']))[0];
 const sid=j.source_input_id;
 const path=(await db.query('select storage_path from source_inputs where id=$1',[sid])).rows[0].storage_path;
 await as(1,"insert into storage.objects(bucket_id,name) values('passo-originals',$1)",[path]);
 await as(1,'select public.passo_enqueue_document(1,$1)',[j.id]);
 const claim=async()=>(await db.query('select * from public.passo_claim_document()')).rows[0];
 const finish=async(job,p)=>(await db.query('select public.passo_worker_finish($1,$2,$3) ok',[job.id,job.lease_token,p])).rows[0].ok;
 const payload={records:[{type_name:'reread test',occurred_at:'2026-11-16',data:{quantity:{version:'cell-state-v1',raw:'-',value:null,status:'explicit_dash'}}}],spans:{quantity:[{rec:0,page:1,box:[1,2,3,4]}]}};
 await finish(await claim(),payload);
 const preview=async()=>(await as(1,'select public.passo_source_preview(1,$1) p',[sid]))[0].p;
 const reread=async(key,revision,model='claude-haiku-5-5',n=1)=> (await as(n,'select (public.passo_reread_source(1,$1,$2,$3,$4,$5,$6,$7)).*',[sid,key,revision,model,'a'.repeat(64),'image/png',120]))[0];
 let s=await preview();
 await denied('published source cannot be reread',()=>reread(uid(1801),s.revision));
 await as(1,'select public.passo_reopen_source(1,$1,$2)',[sid,s.revision]);
 s=await preview();const oldId=s.records[0].id,oldCard=s.pending[0].id;
 for(const n of [2,3,5]) await denied('reread denied for foreign/viewer/uploader '+n,()=>reread(uid(1801),s.revision,'claude-haiku-5-5',n));
 await denied('unapproved model rejected',()=>reread(uid(1801),s.revision,'arbitrary-model'));
 await denied('stale source preview cannot start reread',()=>reread(uid(1801),'0'.repeat(32)));
 let next=await reread(uid(1801),s.revision);
 check('reread queues chosen model on same source',next.source_input_id===sid&&next.model_id==='claude-haiku-5-5'&&next.status==='queued');
 check('lost response retry returns same job',(await reread(uid(1801),s.revision)).id===next.id);
 await denied('same key different model conflicts',()=>reread(uid(1801),s.revision,'claude-opus-5-5'));
 await denied('two active rereads cannot duplicate records',()=>reread(uid(1802),s.revision));
 check('queueing preserves existing records and cards',(await preview()).revision===s.revision);
 next=await claim();
 await db.query('update passo_jobs set attempts=3 where id=$1',[next.id]);
 await db.query('select public.passo_worker_fail($1,$2)',[next.id,next.lease_token]);
 check('model failure preserves source and old review',(await preview()).revision===s.revision);
 const retry=await reread(uid(1802),s.revision,'claude-opus-5-5');next=await claim();
 check('fresh reread does not reuse old model checkpoint',(await db.query('select * from passo_checkpoints where job_id=$1',[retry.id])).rows.length===0);
 try {await finish(next,{...payload,records:[payload.records[0],{...payload.records[0],occurred_at:'invalid'}]});throw Error('expected invalid date');}catch(e){if(e.code!=='22007')throw e;}
 check('partial replacement rolls back old records and cards',(await preview()).revision===s.revision);
 check('successful reread publishes new review',await finish(next,payload));
 const fresh=await preview();
 check('same source has exactly one fresh unconfirmed record',fresh.records.length===1&&fresh.records[0].id!==oldId&&fresh.records[0].status==='대기');
 check('fresh review contains selected model and replaces old card',fresh.pending.length===1&&fresh.pending[0].id!==oldCard&&fresh.pending[0].payload.model==='claude-opus-5-5');
 check('original and dash evidence preserved',fresh.source.storage_path===path&&fresh.records[0].data.quantity.status==='explicit_dash'&&fresh.source.spans.quantity[0].rec===0);
 check('duplicate completion does not replace again',!await finish(next,payload));
 await denied('legacy confirm cannot bypass reread review',()=>as(1,'select public.passo_confirm_document(1,$1)',[next.id]));
 const policy=(await as(1,'select public.passo_policy_preview(1,$1) p',[sid]))[0].p;
 check('reread card always requires human confirmation',policy.items.every(q=>!q.decision.eligible));
 await as(1,'select public.passo_answer_read(1,$1,$2,$3)',[fresh.pending[0].id,fresh.revision,'accept']);
 check('fresh review confirmation restores aggregate record',(await preview()).records[0].status==='확정');
 // Undo the confirmation then edit while a new model job is running.
 const audit=(await db.query("select id from passo_audit where operation='문서 확인' and tenant_id=1 order by id desc limit 1")).rows[0];
 await as(1,'select public.passo_undo(1,$1)',[audit.id]);s=await preview();
 await reread(uid(1803),s.revision);next=await claim();
 await as(1,'select * from public.passo_edit_cells(1,$1,$2,$3)',[s.records[0].id,s.records[0].data,{quantity:7}]);
 const changed=await preview();
 check('concurrent user edit stops reread publication',!await finish(next,payload));
 check('source conflict preserves user data',(await preview()).revision===changed.revision);
 check('source conflict has actionable terminal status',(await db.query('select error_code,status from passo_jobs where id=$1',[next.id])).rows[0].error_code==='source_changed');
 // A legacy original is bound to both tenant and source, and uses its original bucket.
 await db.query("insert into storage.buckets(id,name) values('uploads','uploads') on conflict do nothing");
 const legacyPath=`uploads/1-${sid}.jpg`;
 await db.query('update source_inputs set storage_path=$1 where id=$2',[legacyPath,sid]);
 await db.query("insert into storage.objects(bucket_id,name) values('uploads',$1)",[legacyPath]);
 s=await preview();
 const legacy=await reread(uid(1804),s.revision);
 check('legacy source queues with legacy bucket',legacy.original_bucket==='uploads');
 await db.query('delete from source_inputs where id=$1',[sid]);
 await db.query('delete from storage.objects where name in ($1,$2)',[path,legacyPath]);
}
